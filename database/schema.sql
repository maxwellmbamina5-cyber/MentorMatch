-- MentorMatch PostgreSQL schema.
-- Create the database first (createdb mentormatch), then run:
-- psql -d mentormatch -f database/schema.sql

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    email VARCHAR(255) NOT NULL,
    phone VARCHAR(40) NOT NULL,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL CHECK (role IN ('admin', 'mentor', 'mentee')),
    programme VARCHAR(255) DEFAULT NULL,
    year_of_study VARCHAR(30) DEFAULT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'pending',
    api_token VARCHAR(255) DEFAULT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT users_email_unique UNIQUE (email),
    CONSTRAINT users_phone_unique UNIQUE (phone),
    CONSTRAINT users_api_token_unique UNIQUE (api_token)
);
CREATE INDEX IF NOT EXISTS users_role_status_idx ON users (role, status);

CREATE TABLE IF NOT EXISTS subscriptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    amount DECIMAL(10,2) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'active', 'expired', 'rejected')),
    requested_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    approved_at TIMESTAMP DEFAULT NULL,
    expires_at TIMESTAMP DEFAULT NULL,
    reviewed_by BIGINT DEFAULT NULL REFERENCES users (id) ON DELETE SET NULL,
    reviewed_at TIMESTAMP DEFAULT NULL
);
CREATE INDEX IF NOT EXISTS subscriptions_user_status_idx ON subscriptions (user_id, status, expires_at);
CREATE INDEX IF NOT EXISTS subscriptions_status_requested_idx ON subscriptions (status, requested_at);

CREATE TABLE IF NOT EXISTS system_settings (
    setting_key VARCHAR(100) PRIMARY KEY,
    setting_value TEXT NOT NULL,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS semesters (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    semester_name VARCHAR(100) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    registration_open DATE NOT NULL,
    registration_close DATE NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'upcoming'
);
CREATE INDEX IF NOT EXISTS semesters_status_idx ON semesters (status);
CREATE INDEX IF NOT EXISTS semesters_start_date_idx ON semesters (start_date);

CREATE TABLE IF NOT EXISTS courses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_code VARCHAR(40) NOT NULL CONSTRAINT courses_course_code_unique UNIQUE,
    course_name VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS mentor_applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mentor_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    semester_id BIGINT NOT NULL REFERENCES semesters (id) ON DELETE CASCADE,
    course_code VARCHAR(40) NOT NULL,
    course_name VARCHAR(255) NOT NULL,
    grade VARCHAR(10) DEFAULT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'pending',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reviewed_by BIGINT DEFAULT NULL REFERENCES users (id) ON DELETE SET NULL,
    reviewed_at TIMESTAMP DEFAULT NULL,
    comments TEXT DEFAULT NULL
);
CREATE INDEX IF NOT EXISTS mentor_applications_mentor_idx ON mentor_applications (mentor_id);
CREATE INDEX IF NOT EXISTS mentor_applications_semester_status_idx ON mentor_applications (semester_id, status);

CREATE TABLE IF NOT EXISTS mentee_enrollments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mentee_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    semester_id BIGINT NOT NULL REFERENCES semesters (id) ON DELETE CASCADE,
    course_code VARCHAR(40) NOT NULL,
    course_name VARCHAR(255) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'pending',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reviewed_by BIGINT DEFAULT NULL REFERENCES users (id) ON DELETE SET NULL,
    reviewed_at TIMESTAMP DEFAULT NULL,
    comments TEXT DEFAULT NULL
);
CREATE INDEX IF NOT EXISTS mentee_enrollments_mentee_idx ON mentee_enrollments (mentee_id);
CREATE INDEX IF NOT EXISTS mentee_enrollments_semester_status_idx ON mentee_enrollments (semester_id, status);

CREATE TABLE IF NOT EXISTS mentor_rates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mentor_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    course_code VARCHAR(40) NOT NULL,
    rate_per_hour DECIMAL(12,2) NOT NULL,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT mentor_rates_mentor_course_unique UNIQUE (mentor_id, course_code)
);

CREATE TABLE IF NOT EXISTS mentor_availability (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mentor_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    day_of_week SMALLINT NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    is_recurring SMALLINT NOT NULL DEFAULT 1 CHECK (is_recurring IN (0, 1))
);
CREATE INDEX IF NOT EXISTS mentor_availability_mentor_day_idx ON mentor_availability (mentor_id, day_of_week);

CREATE TABLE IF NOT EXISTS sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mentor_id BIGINT NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    mentee_id BIGINT NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    semester_id BIGINT NOT NULL REFERENCES semesters (id) ON DELETE RESTRICT,
    course_code VARCHAR(40) NOT NULL,
    session_date TIMESTAMP NOT NULL,
    duration_minutes INTEGER NOT NULL,
    mentor_rate DECIMAL(12,2) NOT NULL,
    total_amount DECIMAL(12,2) NOT NULL,
    admin_fee DECIMAL(12,2) NOT NULL DEFAULT 0,
    mentor_payout DECIMAL(12,2) NOT NULL DEFAULT 0,
    status VARCHAR(30) NOT NULL DEFAULT 'pending',
    payment_status VARCHAR(30) NOT NULL DEFAULT 'pending',
    payment_date TIMESTAMP DEFAULT NULL,
    payout_date TIMESTAMP DEFAULT NULL,
    transaction_id VARCHAR(255) DEFAULT NULL CONSTRAINT sessions_transaction_id_unique UNIQUE,
    payment_method VARCHAR(50) DEFAULT NULL,
    meeting_link TEXT DEFAULT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS sessions_mentor_date_idx ON sessions (mentor_id, session_date);
CREATE INDEX IF NOT EXISTS sessions_mentee_date_idx ON sessions (mentee_id, session_date);
CREATE INDEX IF NOT EXISTS sessions_semester_idx ON sessions (semester_id);
CREATE INDEX IF NOT EXISTS sessions_status_payment_idx ON sessions (status, payment_status);

CREATE TABLE IF NOT EXISTS feedback (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES sessions (id) ON DELETE CASCADE,
    mentee_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    mentor_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    rating SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comments TEXT DEFAULT NULL,
    submitted_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS feedback_session_idx ON feedback (session_id);
CREATE INDEX IF NOT EXISTS feedback_mentor_submitted_idx ON feedback (mentor_id, submitted_at);
CREATE INDEX IF NOT EXISTS feedback_mentee_idx ON feedback (mentee_id);

CREATE TABLE IF NOT EXISTS payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES sessions (id) ON DELETE CASCADE,
    mentee_id BIGINT NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    mentor_id BIGINT NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    amount DECIMAL(12,2) NOT NULL,
    admin_fee DECIMAL(12,2) NOT NULL DEFAULT 0,
    mentor_payout DECIMAL(12,2) NOT NULL DEFAULT 0,
    payment_status VARCHAR(30) NOT NULL DEFAULT 'pending',
    transaction_reference VARCHAR(255) NOT NULL CONSTRAINT payments_transaction_reference_unique UNIQUE,
    payment_method VARCHAR(50) NOT NULL DEFAULT 'mobile_money',
    payment_date TIMESTAMP DEFAULT NULL,
    payout_date TIMESTAMP DEFAULT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS payments_session_idx ON payments (session_id);
CREATE INDEX IF NOT EXISTS payments_status_created_idx ON payments (payment_status, created_at);
CREATE INDEX IF NOT EXISTS payments_mentee_idx ON payments (mentee_id);
CREATE INDEX IF NOT EXISTS payments_mentor_idx ON payments (mentor_id);

CREATE TABLE IF NOT EXISTS payout_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mentor_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    amount DECIMAL(12,2) NOT NULL,
    payment_method VARCHAR(50) NOT NULL,
    phone_number VARCHAR(40) DEFAULT NULL,
    account_details TEXT DEFAULT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'pending',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    processed_by BIGINT DEFAULT NULL REFERENCES users (id) ON DELETE SET NULL,
    processed_at TIMESTAMP DEFAULT NULL
);
CREATE INDEX IF NOT EXISTS payout_requests_mentor_status_idx ON payout_requests (mentor_id, status);

CREATE TABLE IF NOT EXISTS certificates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mentor_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    semester_id BIGINT NOT NULL REFERENCES semesters (id) ON DELETE CASCADE,
    total_hours DECIMAL(10,2) NOT NULL DEFAULT 0,
    total_sessions INTEGER NOT NULL DEFAULT 0,
    issue_date DATE NOT NULL,
    certificate_hash VARCHAR(128) NOT NULL CONSTRAINT certificates_hash_unique UNIQUE,
    status VARCHAR(30) NOT NULL DEFAULT 'issued',
    CONSTRAINT certificates_mentor_semester_unique UNIQUE (mentor_id, semester_id)
);

CREATE TABLE IF NOT EXISTS system_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT DEFAULT NULL,
    action TEXT NOT NULL,
    ip_address VARCHAR(64) DEFAULT NULL,
    user_agent TEXT DEFAULT NULL,
    details TEXT DEFAULT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS system_logs_created_at_idx ON system_logs (created_at);
CREATE INDEX IF NOT EXISTS system_logs_user_idx ON system_logs (user_id);

CREATE TABLE IF NOT EXISTS admin_revenue (
    semester_id BIGINT PRIMARY KEY REFERENCES semesters (id) ON DELETE CASCADE,
    total_fees_collected DECIMAL(14,2) NOT NULL DEFAULT 0,
    total_payouts_made DECIMAL(14,2) NOT NULL DEFAULT 0,
    total_service_fees DECIMAL(14,2) NOT NULL DEFAULT 0
);

DROP TRIGGER IF EXISTS system_settings_set_updated_at ON system_settings;
CREATE TRIGGER system_settings_set_updated_at
BEFORE UPDATE ON system_settings
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS mentor_rates_set_updated_at ON mentor_rates;
CREATE TRIGGER mentor_rates_set_updated_at
BEFORE UPDATE ON mentor_rates
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS sessions_set_updated_at ON sessions;
CREATE TRIGGER sessions_set_updated_at
BEFORE UPDATE ON sessions
FOR EACH ROW EXECUTE FUNCTION set_updated_at();
